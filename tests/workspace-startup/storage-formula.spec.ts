import { expect, test } from '@playwright/test';
import type { } from './storageFixture';
import { startStorageFixture } from './storageSupport';

let site: Awaited<ReturnType<typeof startStorageFixture>>;
test.beforeAll(async () => { site = await startStorageFixture('formula'); });
test.afterAll(async () => site.close());

test('10k rows: formula definition and cached reads write no payloads; editing one source writes one chunk and page', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${site.origin}/probe`);
  const result = await page.evaluate(async () => {
    const api = window.workspaceStorageFixture;
    await api.initialize(10_000, 2);
    const original = api.data.tables[0];
    const [priceId, countId] = original.columns.map(column => column.id);
    const table = { ...original, columns: original.columns.map(column => ({ ...column, inputType: 'number' as const })), rows: original.rows.map(row => ({ ...row, values: { [priceId]: 1200, [countId]: 6 } })) };
    api.data = { ...api.data, tables: [table] };
    await api.db.saveWorkspace(api.data);
    const column = { ...api.model.createColumn('平均', 'number'), formula: { version: 1 as const, expression: 'price / count', variables: { price: { columnId: priceId }, count: { columnId: countId } } } };
    const payloadWrites = () => Object.fromEntries(['rowChunks', 'rowPages', 'rowOrderPages'].map(store => [store, api.writes.filter(write => write.store === store).length]));
    api.instrument();
    api.writes = []; api.reads = [];
    const addAction = { type: 'add-column' as const, column, index: table.columns.length };
    api.data = api.history.applyWorkspaceTableHistoryAction(api.data, table.id, addAction, 'redo');
    await api.db.saveWorkspace(api.data, { mutation: { tableId: table.id, action: addAction } });
    const added = payloadWrites();
    const source = api.data.tables[0];
    const replacement = api.prepareWorkspaceColumnSave(source, { ...column, formula: { ...column.formula, expression: 'price / count + 1' } });
    api.data = { ...api.data, tables: [replacement.table] };
    api.writes = [];
    await api.db.saveWorkspace(api.data);
    const changedFormula = payloadWrites();
    const roundedSource = api.data.tables[0];
    const computedColumn = roundedSource.columns[2];
    const rounded = api.prepareWorkspaceColumnSave(roundedSource, { ...computedColumn, formula: { ...computedColumn.formula!, decimalPlaces: 2 } });
    api.data = { ...api.data, tables: [rounded.table] };
    api.writes = [];
    await api.db.saveWorkspace(api.data);
    const changedPrecision = payloadWrites();
    let evaluations = 0;
    const reader = api.createWorkspaceValueReader((plan, row) => { evaluations++; return api.evaluateWorkspaceFormula(plan, row); });
    const calculated = api.data.tables[0].columns[2];
    api.writes = []; api.reads = [];
    for (const row of source.rows) reader.read(row, calculated);
    const warmEvaluations = evaluations;
    for (const row of source.rows) reader.read(row, calculated);
    const cachedEvaluations = evaluations - warmEvaluations;
    const calculationReads = api.reads.length, calculationWrites = api.writes.length;
    const row = source.rows[5000];
    const edit = { type: 'set-cell' as const, rowId: row.id, columnId: priceId, before: 1200, after: 1800 };
    api.data = api.history.applyWorkspaceTableHistoryAction(api.data, table.id, edit, 'redo');
    await api.db.saveWorkspace(api.data, { mutation: { tableId: table.id, action: edit } });
    const sourceEdit = payloadWrites();
    for (const row of api.data.tables[0].rows) reader.read(row, calculated);
    const changedEvaluations = evaluations - warmEvaluations;
    const value = reader.read(api.data.tables[0].rows[5000], calculated).value;
    const loaded = (await api.db.loadWorkspace()).tables[0];
    const reopenedValue = api.createWorkspaceValueReader().read(loaded.rows[5000], loaded.columns[2]).value;
    const imported = await api.spreadsheet.importWorkspaceXlsx(api.spreadsheet.exportWorkspaceXlsx(api.data, loaded), { preserveIds: true });
    return { added, changedFormula, changedPrecision, rowsSame: replacement.table.rows === source.rows && rounded.table.rows === roundedSource.rows, precision: loaded.columns[2].formula?.decimalPlaces, importedPrecision: imported.table!.columns[2].formula?.decimalPlaces, warmEvaluations, cachedEvaluations, calculationReads, calculationWrites, sourceEdit, changedEvaluations, value, reopenedValue, sparse: loaded.rows.every(row => !Object.hasOwn(row.values, column.id)), roundTrip: api.createWorkspaceValueReader().read(imported.table!.rows[5000], imported.table!.columns[2]).value };
  });
  expect(result.added).toEqual({ rowChunks: 0, rowPages: 0, rowOrderPages: 0 });
  expect(result.changedFormula).toEqual(result.added);
  expect(result.changedPrecision).toEqual(result.added);
  expect(result.precision).toBe(2);
  expect(result.importedPrecision).toBe(2);
  expect(result.rowsSame).toBe(true);
  expect(result.warmEvaluations).toBe(10_000);
  expect(result.cachedEvaluations).toBe(0);
  expect(result.calculationReads).toBe(0);
  expect(result.calculationWrites).toBe(0);
  expect(result.sourceEdit).toEqual({ rowChunks: 1, rowPages: 1, rowOrderPages: 0 });
  expect(result.changedEvaluations).toBe(1);
  expect(result.value).toBe(301);
  expect(result.reopenedValue).toBe(301);
  expect(result.roundTrip).toBe(301);
  expect(result.sparse).toBe(true);
  expect(errors).toEqual([]);
});
